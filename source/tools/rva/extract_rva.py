#!/usr/bin/env python3
"""Extract every hard-coded D2Client-relative address from the D2Android mod source.

The mod is a single translation unit (mod/d2mod.c #includes the other .c files),
so all `#define RVA_*` macros end up in one namespace. This script collects them
into a manifest, which is the input for the version mapper (rvamap.py) and for
the generated per-version offset header.

Usage:
    python3 extract_rva.py <source/mod dir> [--json out.json] [--csv out.csv] [--header out.h]
"""
import argparse
import json
import os
import re
import sys

DEFINE_RE = re.compile(r"^#define\s+(RVA_[A-Za-z0-9_]+)\s+(0x[0-9A-Fa-f]+)\b")
INLINE_RE = re.compile(r"client\s*\+\s*0x([0-9A-Fa-f]+)")


def scan(mod_dir):
    defines, inline = [], []
    for name in sorted(os.listdir(mod_dir)):
        if not name.endswith((".c", ".h")):
            continue
        path = os.path.join(mod_dir, name)
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for lineno, line in enumerate(fh, 1):
                m = DEFINE_RE.match(line)
                if m:
                    defines.append({
                        "name": m.group(1),
                        "value": int(m.group(2), 16),
                        "file": name,
                        "line": lineno,
                    })
                for m2 in INLINE_RE.finditer(line):
                    inline.append({
                        "value": int(m2.group(1), 16),
                        "file": name,
                        "line": lineno,
                        "text": line.strip()[:120],
                    })
    return defines, inline


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mod_dir")
    ap.add_argument("--json")
    ap.add_argument("--csv")
    ap.add_argument("--header")
    args = ap.parse_args()

    defines, inline = scan(args.mod_dir)

    dup = {}
    for d in defines:
        dup.setdefault(d["name"], []).append(d)
    clashes = {k: v for k, v in dup.items() if len(v) > 1}

    print(f"defines: {len(defines)} unique names: {len(dup)}")
    print(f"inline client+0x sites: {len(inline)}")
    if clashes:
        print(f"WARNING: duplicate names: {list(clashes)[:10]}", file=sys.stderr)

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"image": "client", "count": len(defines),
                       "defines": defines, "inline": inline}, fh, indent=2)
        print("wrote", args.json)

    if args.csv:
        with open(args.csv, "w", encoding="utf-8") as fh:
            fh.write("name,rva,file,line\n")
            for d in defines:
                fh.write(f"{d['name']},0x{d['value']:X},{d['file']},{d['line']}\n")
        print("wrote", args.csv)

    if args.header:
        with open(args.header, "w", encoding="utf-8") as fh:
            fh.write("/* generated by tools/extract_rva.py - do not edit */\n")
            fh.write(f"/* {len(defines)} D2Client-relative addresses */\n")
            last_file = None
            for d in defines:
                if d["file"] != last_file:
                    fh.write(f"\n/* {d['file']} */\n")
                    last_file = d["file"]
                fh.write(f"#define {d['name']} 0x{d['value']:X}\n")
        print("wrote", args.header)


if __name__ == "__main__":
    main()
